package ru.mirea.examgitgud.model;

/**
 * Статус задания в банке заданий. Задание преподавателя попадает в банк
 * только после модерации (требования 2.1 и 3.1).
 */
public enum TaskStatus {
    /** Черновик преподавателя. */
    DRAFT,
    /** Отправлено на модерацию. */
    ON_MODERATION,
    /** Опубликовано и доступно студентам. */
    PUBLISHED,
    /** Отклонено модератором. */
    REJECTED
}
