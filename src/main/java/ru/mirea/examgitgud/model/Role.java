package ru.mirea.examgitgud.model;

/**
 * Роль пользователя платформы. От роли зависят доступные разделы и права в API.
 */
public enum Role {
    /** Студент: решает задания, проходит пробные экзамены, смотрит статистику. */
    STUDENT,
    /** Преподаватель: создаёт задания и тесты, ведёт группы. */
    TEACHER,
    /** Администратор: модерирует контент и управляет пользователями. */
    ADMIN
}
